/**
 * The description's types, generated from `description.schema.json`, the one
 * place its shape is stated: `npm run describe` writes them to
 * {@link SCHEMA_TYPES}, and `description.ts` names what it reads from there.
 * Each schema `description` becomes the JSDoc an editor shows.
 */

import { compile, type JSONSchema } from "json-schema-to-typescript";
import { GENERATED } from "./sources.ts";

/** Where the generated types are written. */
export const SCHEMA_TYPES = `${GENERATED}/describe/description.schema.ts`;

/** Keywords that only validate: they say which fields go together, which a
 * type cannot, and the generator would read them as an open object. */
const VALIDATION_ONLY = new Set(["if", "then", "else", "dependentRequired", "not"]);

/** Whether a branch of `anyOf` or `oneOf` only asks for fields, adding none. */
const onlyRequires = (branch: unknown): boolean =>
  typeof branch === "object" &&
  branch !== null &&
  Object.keys(branch).every((k) => k === "required" || k === "description");

/** The schema with what only validates taken out, at every depth. */
function typed(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(typed);
  if (typeof node !== "object" || node === null) return node;
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(node)) {
    if (VALIDATION_ONLY.has(k)) continue;
    const t = typed(v);
    if ((k === "anyOf" || k === "oneOf") && Array.isArray(t) && t.every(onlyRequires))
      continue;
    out[k] = t;
  }
  // The fields a node requires bind each of its branches, which the
  // generator reads apart from it.
  const required = out["required"];
  for (const key of ["oneOf", "anyOf"])
    if (Array.isArray(required) && Array.isArray(out[key]))
      out[key] = (out[key] as Record<string, unknown>[]).map((b) =>
        typeof b["properties"] === "object" && b["properties"] !== null
          ? {
              ...b,
              required: [
                ...new Set([
                  ...((b["required"] as string[] | undefined) ?? []),
                  ...required.filter((r: string) => r in (b["properties"] as object)),
                ]),
              ],
            }
          : b,
      );
  // Fields beside the named ones: TypeScript holds every named field to the
  // index signature too, so the signature takes each named field's type, and
  // `undefined` for those left out.
  const { properties, additionalProperties } = out;
  if (
    typeof properties === "object" &&
    properties !== null &&
    typeof additionalProperties === "object" &&
    additionalProperties !== null
  )
    out["additionalProperties"] = {
      anyOf: [
        additionalProperties,
        ...Object.values(properties),
        { tsType: "undefined" },
      ],
    };
  // A `$ref` beside keywords of its own adds to what it names (2020-12). The
  // generator reads only the `$ref`, or, beside a description, declares a
  // second copy of what it names: so it is written as the `allOf` it is.
  const { $ref, description, type: _, unevaluatedProperties: __, ...rest } = out;
  if (typeof $ref !== "string" || Object.keys(out).length === 1) return out;
  return {
    ...(description === undefined ? {} : { description }),
    allOf: Object.keys(rest).length === 0 ? [{ $ref }] : [{ $ref }, rest],
  };
}

/** The TypeScript the schema's `$defs` declare, each by its name, and
 * `DescriptionFile`, a game's description or a library. */
export async function schemaTypes(schema: Record<string, unknown>): Promise<string> {
  const root = typed(schema) as Record<string, unknown>;
  root["oneOf"] = [{ $ref: "#/$defs/game" }, { $ref: "#/$defs/library" }];
  delete root["title"];
  const body = await compile(root as JSONSchema, "DescriptionFile", {
    additionalProperties: false,
    bannerComment: "",
    declareExternallyReferenced: true,
    ignoreMinAndMaxItems: true,
    unreachableDefinitions: true,
    format: true,
  });
  return `// Generated by \`npm run describe\` from src/describe/description.schema.json.\n\n${body}`;
}
